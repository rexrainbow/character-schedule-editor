import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import example from '../../src/examples/state-example.json' with { type: 'json' };
import { navigate, exportProject } from './navigation.js';

test('builtin uses shared task fields, locks structure, and custom labels survive language changes and project reload', async ({ page }) => {
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.locator('.app-header input[type=file]').first().setInputFiles({ name: 'project.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(example)) });
  await navigate(page, 'tasks');
  await page.locator('.operand-sidebar').getByRole('button', { name: 'Set variable', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Add parameter', exact: true })).toBeDisabled();
  await expect(page.locator('.parameter-row')).toHaveCount(2);
  for (const select of await page.getByRole('combobox', { name: 'Parameter type', exact: true }).all()) await expect(select).toBeDisabled();
  for (const button of await page.locator('.parameter-row .row-actions button').all()) await expect(button).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Task actions', exact: true })).toHaveCount(0);
  await page.getByRole('textbox', { name: 'Display name', exact: true }).fill('Update state');
  await page.getByRole('textbox', { name: 'Engine key', exact: true }).fill('assign_value');
  await page.getByRole('textbox', { name: 'Parameter name', exact: true }).nth(0).fill('Destination');
  await page.getByRole('textbox', { name: 'Parameter name', exact: true }).nth(1).fill('New value');
  await page.locator('.schedule-titlebar .icon-field').click();
  await page.getByRole('dialog').getByRole('button', { name: 'Work', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Apply', exact: true }).click();
  await navigate(page, 'slots');
  await expect(page.getByRole('combobox', { name: 'Task', exact: true }).first().locator('option[value="builtin:set_variable"]')).toHaveText('Update state');
  await page.locator('.sidebar').getByRole('button', { name: /工作/ }).click();
  await expect(page.getByRole('button', { name: 'Destination', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'New value', exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('zh-TW');
  await expect(page.getByRole('button', { name: 'Destination', exact: true })).toBeVisible();
  await expect(page.locator('.sidebar')).toContainText('Update state');
  const wait = page.waitForEvent('download'); await exportProject(page);
  const saved = JSON.parse(await readFile(await (await wait).path(), 'utf8'));
  expect(saved.builtin_tasks.set_variable.icon).toBe('tabler:briefcase');
  expect(saved.builtin_tasks.set_variable.symbol).toBe('assign_value');
  await page.locator('.app-header input[type=file]').first().setInputFiles({ name: 'saved.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(saved)) });
  await navigate(page, 'tasks', 'zh-TW');
  await page.locator('.operand-sidebar').getByRole('button', { name: 'Update state', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '顯示名稱', exact: true })).toHaveValue('Update state');
  expect(errors).toEqual([]);
});
