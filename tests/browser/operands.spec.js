async function load(page, data = example) {
  await page.goto('/');
  await page.locator('.app-header input[type=file]').first().setInputFiles({ name: 'operands.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(data)) });
  await expect(page.getByRole('status')).toContainText('JSON imported successfully.');
}
async function exported(page) {
  const wait = page.waitForEvent('download'); await exportProject(page);
  return JSON.parse(await readFile(await (await wait).path(), 'utf8'));
}
const node = (page, name) => page.getByRole('treeitem', { name, exact: true });
async function constant(page, operand, type, value, container = page) {
  await container.getByRole('button', { name: operand, exact: true }).click();
  const modal = page.getByRole('dialog'); await modal.getByRole('tab', { name: 'Constant', exact: true }).click();
  await modal.getByRole('combobox', { name: 'Constant type', exact: true }).selectOption(type);
  if (type === 'boolean') await modal.getByRole('combobox', { name: 'Constant value', exact: true }).selectOption(value);
  else await modal.getByRole(type === 'number' ? 'spinbutton' : 'textbox', { name: 'Constant value', exact: true }).fill(value);
  await modal.getByRole('button', { name: 'Apply', exact: true }).click();
}

test('tree CRUD, subtree copies, reparenting, ordering and rename keep UUID links intact', async ({ page }) => {
  const errors = []; page.on('pageerror', (e) => errors.push(e.message));
  await load(page); await navigate(page, 'operands');
  const up = page.locator('.tree-actions').getByRole('button', { name: 'Move up', exact: true });
  const down = page.locator('.tree-actions').getByRole('button', { name: 'Move down', exact: true });
  await expect(up).toBeDisabled(); await expect(down).toBeDisabled();
  await expect(page.locator('.node-properties .row-actions')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Delete node', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Group', exact: true }).click();
  await page.getByRole('textbox', { name: 'Node name', exact: true }).fill('Status');
  await page.getByRole('button', { name: 'Value', exact: true }).click();
  await page.getByRole('textbox', { name: 'Node name', exact: true }).fill('Healthy');
  await page.getByRole('combobox', { name: 'Value type', exact: true }).selectOption('boolean');
  await node(page, 'Status').click(); await page.getByRole('button', { name: 'Duplicate subtree', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Node name', exact: true })).toHaveValue('Status (副本)');
  let saved = await exported(page); const ids = Object.keys(saved.operand_nodes);
  const original = ids.find((id) => saved.operand_nodes[id].display_name === 'Status');
  const copy = ids.find((id) => saved.operand_nodes[id].display_name === 'Status (副本)');
  await expect(down).toBeDisabled();
  await up.click();
  await expect(node(page, 'Status (副本)')).toHaveAttribute('aria-selected', 'true');
  const swapped = (await exported(page)).operand_nodes;
  expect(swapped[copy].order + 1).toBe(swapped[original].order);
  expect(Object.entries(swapped).filter(([, n]) => n.parent_id === copy)).toEqual(Object.entries(saved.operand_nodes).filter(([, n]) => n.parent_id === copy));
  await down.click();
  expect(ids.filter((id) => saved.operand_nodes[id].display_name === 'Healthy')).toHaveLength(2);
  expect(ids.find((id) => saved.operand_nodes[id].parent_id === copy)).not.toBe(ids.find((id) => saved.operand_nodes[id].parent_id === original));
  await expect(page.getByRole('button', { name: 'Delete node', exact: true })).toBeEnabled();
  page.once('dialog', async (dialog) => { expect(dialog.message()).toContain('2 nodes'); await dialog.dismiss(); });
  await page.getByRole('button', { name: 'Delete node', exact: true }).click();
  expect((await exported(page)).operand_nodes).toEqual(saved.operand_nodes);
  page.once('dialog', async (dialog) => { expect(dialog.message()).toContain('all descendants'); await dialog.accept(); });
  await page.getByRole('button', { name: 'Delete node', exact: true }).click();
  const deleted = (await exported(page)).operand_nodes;
  expect(deleted[copy]).toBeUndefined();
  expect(Object.values(deleted).filter((n) => n.display_name === 'Healthy')).toHaveLength(1);
  expect(deleted[original]).toBeDefined();
  await node(page, 'Character').click();
  await expect(page.getByRole('button', { name: 'Delete node', exact: true })).toBeDisabled();
  await expect(page.locator('.shared-warning')).toContainText('Character.energy');
  await node(page, 'energy').click();
  await page.locator('.parent-picker').click();
  await page.getByRole('dialog').getByRole('treeitem', { name: 'Status', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Apply', exact: true }).click();
  await page.getByRole('textbox', { name: 'Node name', exact: true }).fill('Stamina');
  await expect(page.getByRole('button', { name: 'Delete node', exact: true })).toBeDisabled();
  await page.getByRole('combobox', { name: 'Value type', exact: true }).selectOption('string');
  await expect(page.getByRole('combobox', { name: 'Value type', exact: true })).toHaveValue('number');
  await expect(page.getByRole('alert')).toContainText('Type was not changed');
  await expect(page.getByRole('spinbutton', { name: 'Order', exact: true })).toHaveCount(0);
  await page.locator('.tree-actions').getByRole('button', { name: 'Move up', exact: true }).click();
  saved = await exported(page); const energyId = Object.keys(example.operand_nodes).find((id) => example.operand_nodes[id].display_name === 'energy');
  expect(saved.operand_nodes[energyId].parent_id).toBe(original); expect(saved.operand_nodes[energyId].order).toBe(0);
  await page.getByRole('textbox', { name: 'Search variables', exact: true }).fill('Stamina');
  await expect(up).toBeDisabled(); await expect(down).toBeDisabled();
  await expect(node(page, 'Character')).toBeVisible(); await expect(node(page, 'Status')).toBeVisible(); await expect(node(page, 'Healthy')).toHaveCount(0);
  await navigate(page, 'slots');
  await expect(page.getByRole('button', { name: 'Left operand (opA)', exact: true }).nth(1)).toContainText('Character.Status.Stamina');
  expect(errors).toEqual([]);
});

