test('invalid tree and condition imports report locations without replacing the project', async ({ page }) => {
  await load(page);
  const root = Object.keys(example.operand_nodes)[0];
  const bad = structuredClone(example); bad.operand_nodes[root].parent_id = root;
  await page.locator('.app-header input[type=file]').first().setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(bad)) });
  await expect(page.locator('.issues')).toContainText(`/operand_nodes/${root}/parent_id`);
  const badRef = structuredClone(example); Object.values(badRef.slots)[0].branches[0].condition.operand_a.reference_id = crypto.randomUUID();
  await page.locator('.app-header input[type=file]').first().setInputFiles({ name: 'bad-ref.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(badRef)) });
  await expect(page.locator('.issues')).toContainText('/condition/operand_a/reference_id');
  expect((await exported(page)).operand_nodes).toEqual(example.operand_nodes);
});

